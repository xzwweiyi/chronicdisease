    /**
     *  用于判断连个逗号链接的字符串的包含关系
     *  str1 中是否包含str2中的元素
     * @param str1
     * @param str2
     * @return
     */
    public static Boolean isIncludeStr(String str1, String str2) {
        if (StringUtils.isEmpty(str1) || StringUtils.isEmpty(str2)) {
            L.info("str1:{} str2:{}", str1, str2);
            return false;
        }
        String[] str1ArrArrayList = (String[]) Arrays.asList(str1.split(",")).toArray();
        String[] str2ArrArrayList = (String[]) Arrays.asList(str2.split(",")).toArray();
        if (str2ArrArrayList.length == 0 || str1ArrArrayList.length == 0) {
            L.info(" str1ArrArrayList:{}  str2ArrArrayList:{} ", str1ArrArrayList, str2ArrArrayList);
            return false;
        }
        List<String> list1 = Arrays.asList(str1ArrArrayList);
        List<String> list2 = Arrays.asList(str2ArrArrayList);
        for (int i = 0; i < list2.size(); i++) {
            if (list1.contains(list2.get(i))) {
                return true;
            }
            if (i == list2.size() - 1) {
                return false;
            }
        }
        return false;
    }

